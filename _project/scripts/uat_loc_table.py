#!/usr/bin/env python3
"""Generate / check the UAT spec's module-LOC table and per-bucket summary.

uat-spec-module-loc-table-autogen: the manual table in
`_project/specs/uat-framework.md` drifted every time a UAT module grew (it was
hand-corrected twice in a week -- uat-config-schema-spec-realignment and
uat-charter-spec-drift-post-t11). This script owns the volatile numbers so CI
keeps them honest.

What it owns (and only this -- it does NOT redefine which modules or which
lines count, per the parent's anti-pattern):

* the **Actual (…)** column of the `| Module | Responsibility | … |` table --
  updated in place from `wc -l` (raw line count, the rule the manual table
  used), preserving the human-authored Responsibility and estimate columns; and
* the **per-bucket summary** between the ``UAT-LOC-SUMMARY`` markers --
  regenerated from the module→bucket map below.

Usage:
    uv run --project _project/scripts -- python _project/scripts/uat_loc_table.py           # rewrite in place
    uv run --project _project/scripts -- python _project/scripts/uat_loc_table.py --check    # fail on drift (CI)
"""

from __future__ import annotations

import argparse
import difflib
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
SPEC_PATH = REPO_ROOT / "_project" / "specs" / "uat-framework.md"
UAT_DIR = REPO_ROOT / "tests" / "uat"

SUMMARY_BEGIN = "<!-- UAT-LOC-SUMMARY:BEGIN (generated by _project/scripts/uat_loc_table.py; do not hand-edit) -->"
SUMMARY_END = "<!-- UAT-LOC-SUMMARY:END -->"

# Module -> bucket map (the pinned "which modules / which bucket" definition,
# reproduced from the manual table -- NOT redefined here). Module names are the
# spec table's keys; paths resolve under tests/uat/. Order within a bucket is
# cosmetic; the label order is the summary's display order.
BUCKETS: list[tuple[str, list[str]]] = [
    ("plumbing (orchestrator/config/`_cli`)", ["orchestrator.py", "config.py", "_cli.py"]),
    (
        "core exercise (execute/matrix/runner/enumerate/cleanup/ladder)",
        ["phases/execute.py", "matrix.py", "runner.py", "phases/enumerate.py", "cleanup.py", "ladder.py"],
    ),
    (
        "preflight/compat/timeouts",
        ["phases/preflight.py", "compatibility.py", "timeouts.py", "preflight_budget.py"],
    ),
    (
        "Docker lifecycle (default-OFF, incl. `container_cleanup.py`)",
        ["docker_assets.py", "docker_cleanup.py", "container_cleanup.py"],
    ),
    (
        "chartered evidence artifacts (validate/report/package/cells_io/gate_summary)",
        ["phases/validate.py", "phases/report.py", "phases/package.py", "cells_io.py", "gate_summary.py"],
    ),
    ("explorer-prep", ["phases/explorer_smoke.py"]),
    ("throughput", ["throughput.py"]),
    ("artifact hygiene", ["artifact_hygiene.py"]),
    ("package init markers", ["__init__.py", "phases/__init__.py"]),
]

# Every module that must appear in the table exactly once (drift guard: the
# table and the bucket map cannot silently disagree on the module set).
ALL_MODULES: list[str] = [name for _label, names in BUCKETS for name in names]


def loc(module: str) -> int:
    """Raw line count for a module under tests/uat/ (the manual table's rule)."""
    return len((UAT_DIR / module).read_text(encoding="utf-8").splitlines())


def _module_name_from_row(row: str) -> str | None:
    """Extract the ``module`` key from a table data row, or None if not one."""
    cells = row.split("|")
    if len(cells) < 4:
        return None
    first = cells[1].strip()
    if not (first.startswith("`") and first.endswith("`")):
        return None
    return first.strip("`")


def update_table_actuals(text: str) -> str:
    """Rewrite the Actual column of each module row from a fresh `wc -l`.

    Only the last table cell (Actual) is touched; the Responsibility and
    estimate cells are preserved byte-for-byte. Robust to a `|` inside the
    Responsibility prose because the Actual cell is always the second-to-last
    pipe-delimited field.
    """
    out: list[str] = []
    for row in text.splitlines(keepends=False):
        name = _module_name_from_row(row)
        if name is None or name not in ALL_MODULES:
            out.append(row)
            continue
        cells = row.split("|")
        cells[-2] = f" {loc(name)} "
        out.append("|".join(cells))
    return "\n".join(out) + ("\n" if text.endswith("\n") else "")


def render_summary() -> str:
    """Render the per-bucket + total summary block (between the markers)."""
    lines = [SUMMARY_BEGIN, "", "**Per-bucket production LOC** (auto-generated -- run the script to refresh):", ""]
    total = 0
    for label, names in BUCKETS:
        subtotal = sum(loc(n) for n in names)
        total += subtotal
        lines.append(f"- {label}: {subtotal:,}")
    lines.append("")
    lines.append(f"**Total: {total:,} production LOC across {len(ALL_MODULES)} modules.**")
    lines.append("")
    lines.append(SUMMARY_END)
    return "\n".join(lines)


def update_summary(text: str) -> str:
    begin = text.find(SUMMARY_BEGIN)
    end = text.find(SUMMARY_END)
    if begin == -1 or end == -1:
        raise SystemExit(
            f"error: {SPEC_PATH} is missing the UAT-LOC-SUMMARY markers; add them once so the "
            "generator has an anchor to own."
        )
    return text[:begin] + render_summary() + text[end + len(SUMMARY_END) :]


def _validate_table_coverage(text: str) -> None:
    found = {name for row in text.splitlines() if (name := _module_name_from_row(row)) is not None}
    table_uat = found & set(ALL_MODULES)
    missing = set(ALL_MODULES) - table_uat
    if missing:
        raise SystemExit(f"error: bucket map lists modules absent from the spec table: {sorted(missing)}")
    missing_files = [m for m in ALL_MODULES if not (UAT_DIR / m).exists()]
    if missing_files:
        raise SystemExit(f"error: bucket map lists modules absent from tests/uat/: {missing_files}")


def build(text: str) -> str:
    _validate_table_coverage(text)
    return update_summary(update_table_actuals(text))


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate/check the UAT spec module-LOC table + summary.")
    parser.add_argument(
        "--check",
        action="store_true",
        help="Exit non-zero if the committed spec differs from the generated output (CI mode).",
    )
    args = parser.parse_args()

    current = SPEC_PATH.read_text(encoding="utf-8")
    generated = build(current)

    if args.check:
        if generated != current:
            diff = difflib.unified_diff(
                current.splitlines(keepends=True),
                generated.splitlines(keepends=True),
                fromfile="committed",
                tofile="generated",
            )
            sys.stderr.write("".join(diff))
            sys.stderr.write(
                "\nUAT LOC table/summary is stale. Run:\n"
                "  uv run --project _project/scripts -- python _project/scripts/uat_loc_table.py\n"
                "(or `make guards-fix` to regenerate every mechanical drift-guard artifact)\n"
            )
            return 1
        print("UAT LOC table + summary match the tree.")
        return 0

    if generated != current:
        SPEC_PATH.write_text(generated, encoding="utf-8")
        print(f"Updated {SPEC_PATH.relative_to(REPO_ROOT)}")
    else:
        print("UAT LOC table + summary already current.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
